class BuildingService:
    @staticmethod
    def generate_building_code() -> str:
        """Generate next sequence code like PVG-BLD-001."""
        count = Building.query.count()
        code = f"PVG-BLD-{count + 1:03d}"
        while Building.query.filter_by(code=code).first():
            count += 1
            code = f"PVG-BLD-{count + 1:03d}"
        return code

    def check_duplicate_building(self, lat: float, lng: float, name: str = None, radius_meters: float = 50.0) -> dict:
        """
        Check for nearby buildings within `radius_meters` (default 50m) and optional name match.
        """
        # Bounding box approximate filter (1 deg lat ~ 111km, 1 deg lng ~ 108km at 14 deg N)
        lat_delta = radius_meters / 111000.0
        lng_delta = radius_meters / (111000.0 * 0.97)

        candidates = Building.query.filter(
            Building.latitude.between(lat - lat_delta * 1.5, lat + lat_delta * 1.5),
            Building.longitude.between(lng - lng_delta * 1.5, lng + lng_delta * 1.5),
            Building.status != "ARCHIVED"
        ).all()

        nearby = []
        name_clean = (name or "").strip().lower()

        for b in candidates:
            dist = b.distance_to_meters(lat, lng)
            if dist <= radius_meters:
                is_name_match = False
                if name_clean and len(name_clean) > 3 and (name_clean in b.name.lower() or b.name.lower() in name_clean):
                    is_name_match = True

                b_dict = b.to_dict(include_children=False)
                b_dict["distanceMeters"] = round(dist, 1)
                b_dict["nameMatch"] = is_name_match
                nearby.append(b_dict)

        nearby.sort(key=lambda x: x["distanceMeters"])
        return {
            "isDuplicateSuspected": len(nearby) > 0,
            "matchCount": len(nearby),
            "nearbyBuildings": nearby,
        }

    def create_building(self, data: dict, admin_id: int = None, admin_name: str = None) -> Building:
        """Create a new building with optional nested floors and units."""
        name = (data.get("name") or "").strip()
        is_auto_generated = False
        if not name:
            gen_code = self.generate_building_code()
            name = f"Building - {gen_code}"
            is_auto_generated = True

        building_id = data.get("id") or f"bld_{uuid.uuid4().hex[:12]}"
        code = data.get("code") or self.generate_building_code()

        lat = float(data.get("latitude") or 14.1025)
        lng = float(data.get("longitude") or 77.2798)

        # Enforce rule: Only one active building at a given coordinate point (~2-3m threshold)
        existing_at_point = Building.query.filter(
            Building.status != "ARCHIVED",
            Building.latitude.between(lat - 0.00003, lat + 0.00003),
            Building.longitude.between(lng - 0.00003, lng + 0.00003),
        ).first()

        if existing_at_point and not data.get("forceCreateAtPoint"):
            # Update the existing building at this point instead of creating a duplicate
            return self.update_building(existing_at_point.id, data, admin_id=admin_id, admin_name=admin_name)

        building = Building(
            id=building_id,
            code=code,
            name=name,
            kannada_name=data.get("kannadaName"),
            is_name_auto_generated=is_auto_generated or bool(data.get("isNameAutoGenerated", False)),
            address=(data.get("address") or f"Near {data.get('area', 'Pavagada Town')}").strip(),
            area=data.get("area", "Pavagada Town"),
            street=data.get("street"),
            pincode=data.get("pincode", "561202"),
            landmark=data.get("landmark"),
            identification_notes=data.get("identificationNotes"),
            source_of_information=data.get("sourceOfInformation", "Field Survey"),
            building_type=data.get("buildingType", "Commercial"),
            commercial_subtype=data.get("commercialSubtype"),
            secondary_usage=data.get("secondaryUsage"),
            occupancy_status=data.get("occupancyStatus", "Partially occupied"),
            building_condition=data.get("buildingCondition", "Good"),
            construction_status=data.get("constructionStatus", "Completed"),
            building_access_type=data.get("buildingAccessType", "Public Road"),
            total_floors=int(data.get("totalFloors", 1)),
            commercial_units_count=int(data.get("commercialUnitsCount", 0)),
            residential_units_count=int(data.get("residentialUnitsCount", 0)),
            vacant_units_count=int(data.get("vacantUnitsCount", 0)),
            approx_size_sqft=float(data.get("approxSizeSqft")) if data.get("approxSizeSqft") else None,
            road_access_width=data.get("roadAccessWidth"),
            two_wheeler_parking=bool(data.get("twoWheelerParking", True)),
            car_parking=bool(data.get("carParking", False)),
            lift_available=bool(data.get("liftAvailable", False)),
            storage_available=bool(data.get("storageAvailable", False)),
            accessibility_features=data.get("accessibilityFeatures"),
            latitude=lat,
            longitude=lng,
            gps_accuracy=float(data.get("gpsAccuracy")) if data.get("gpsAccuracy") else None,
            entrance_latitude=float(data.get("entranceLatitude")) if data.get("entranceLatitude") else None,
            entrance_longitude=float(data.get("entranceLongitude")) if data.get("entranceLongitude") else None,
            footprint_geojson=data.get("footprintGeojson"),
            map_reference=data.get("mapReference"),
            location_verification_status=data.get("locationVerificationStatus", "VERIFIED" if admin_id else "PENDING"),
            surveyor_id=admin_id,
            surveyor_name=admin_name or data.get("surveyorName", "Admin Surveyor"),
            survey_date=datetime.utcnow(),
            status=data.get("status", "ACTIVE"),
        )
        db.session.add(building)
        db.session.flush()

        # Handle nested initial floors if provided
        floors_data = data.get("floors") or []
        if floors_data:
            for f_idx, f_item in enumerate(floors_data):
                f_id = f_item.get("id") or f"flr_{uuid.uuid4().hex[:10]}"
                floor = Floor(
                    id=f_id,
                    building_id=building.id,
                    floor_level=int(f_item.get("floorLevel", f_idx)),
                    floor_name=f_item.get("floorName", f"Floor {f_idx}"),
                    floor_usage=f_item.get("floorUsage", "Commercial"),
                    units_count=int(f_item.get("unitsCount", 0)),
                    notes=f_item.get("notes"),
                )
                db.session.add(floor)
                db.session.flush()

                # Handle nested units inside this floor
                units_data = f_item.get("units") or []
                for u_idx, u_item in enumerate(units_data):
                    u_id = u_item.get("id") or f"unt_{uuid.uuid4().hex[:10]}"
                    unit = Unit(
                        id=u_id,
                        building_id=building.id,
                        floor_id=floor.id,
                        unit_number=u_item.get("unitNumber", f"Unit {u_idx + 1}"),
                        unit_name=u_item.get("unitName"),
                        unit_type=u_item.get("unitType", "Retail Shop"),
                        usage=u_item.get("usage", "Commercial"),
                        occupancy_status=u_item.get("occupancyStatus", "Occupied"),
                        size_sqft=float(u_item.get("sizeSqft")) if u_item.get("sizeSqft") else None,
                        notes=u_item.get("notes"),
                    )
                    db.session.add(unit)

        # Handle initial photos if provided
        photos_data = data.get("photos") or []
        for p_idx, p_item in enumerate(photos_data):
            p_url = p_item.get("url") if isinstance(p_item, dict) else str(p_item)
            if p_url:
                photo = BuildingPhoto(
                    id=f"bph_{uuid.uuid4().hex[:10]}",
                    building_id=building.id,
                    url=p_url,
                    photo_type=p_item.get("photoType", "Front View") if isinstance(p_item, dict) else "Front View",
                    caption=p_item.get("caption") if isinstance(p_item, dict) else None,
                    is_primary=bool(p_item.get("isPrimary", p_idx == 0)) if isinstance(p_item, dict) else (p_idx == 0),
                    surveyor_name=admin_name or "Admin",
                )
                db.session.add(photo)

        db.session.commit()

        # Audit
        audit_service.log_action(
            admin_email=admin_name or "surveyor",
            action="CREATE_BUILDING",
            entity_type="Building",
            entity_id=building.id,
            admin_id=admin_id,
            new_values={"name": building.name, "type": building.building_type, "code": building.code},
        )

        # Award Gamification points (+50 pts for building, +15 for each photo)
        if admin_id:
            pts = 50 + (len(photos_data) * 15)
            survey_gamification_service.award_points(
                admin_id=admin_id,
                display_name=admin_name or "Surveyor",
                points=pts,
                action_type="BUILDING_MAPPED",
                photos_count=len(photos_data),
            )

        return building

    def update_building(self, building_id: str, data: dict, admin_id: int = None, admin_name: str = None) -> Building:
        building = Building.query.get(building_id)
        if not building:
            raise ValueError(f"Building with id '{building_id}' not found.")

        old_values = {"name": building.name, "type": building.building_type}

        # Update scalar fields
        for field in [
            "name", "kannada_name", "address", "area", "street", "pincode", "landmark",
            "identification_notes", "source_of_information", "building_type", "commercial_subtype",
            "secondary_usage", "occupancy_status", "building_condition", "construction_status",
            "building_access_type", "total_floors", "commercial_units_count", "residential_units_count",
            "vacant_units_count", "approx_size_sqft", "road_access_width", "two_wheeler_parking",
            "car_parking", "lift_available", "storage_available", "accessibility_features",
            "latitude", "longitude", "gps_accuracy", "entrance_latitude", "entrance_longitude",
            "footprint_geojson", "map_reference", "location_verification_status", "status"
        ]:
            camel_key = "".join(word.capitalize() if i > 0 else word for i, word in enumerate(field.split("_")))
            if camel_key in data:
                setattr(building, field, data[camel_key])
            elif field in data:
                setattr(building, field, data[field])

        db.session.commit()

        audit_service.log_action(
            admin_email=admin_name or "surveyor",
            action="UPDATE_BUILDING",
            entity_type="Building",
            entity_id=building.id,
            admin_id=admin_id,
            old_values=old_values,
            new_values={"name": building.name, "type": building.building_type},
        )
        return building

    def get_building_by_id(self, building_id: str, include_children: bool = True) -> Building:
        building = Building.query.get(building_id)
        if not building:
            raise ValueError(f"Building with id '{building_id}' not found.")
        return building

    def delete_building(self, building_id: str, admin_id: int = None, admin_name: str = None, archive_only: bool = True, force: bool = False) -> dict:
        building = Building.query.get(building_id)
        if not building:
            raise ValueError(f"Building with id '{building_id}' not found.")

        # Check associated businesses
        biz_count = 0
        if hasattr(building, "businesses"):
            biz_count = building.businesses.filter_by(status="ACTIVE").count()

        if archive_only:
            # Soft-delete / Archive workflow: safely preserves businesses, floors, units, audit trails
            building.status = "ARCHIVED"
            db.session.commit()

            audit_service.log_action(
                admin_email=admin_name or "admin",
                action="ARCHIVE_BUILDING",
                entity_type="Building",
                entity_id=building.id,
                admin_id=admin_id,
                old_values={"name": building.name, "code": building.code, "status": "ACTIVE"},
                new_values={"status": "ARCHIVED", "preservedBusinesses": biz_count},
            )
            return {"archived": True, "id": building.id, "businessesPreserved": biz_count}

        # Permanent deletion requested
        if biz_count > 0 and not force:
            raise ValueError(
                f"Building has {biz_count} registered business(es). Please archive the building instead to preserve business records, or remove the businesses first."
            )

        audit_service.log_action(
            admin_email=admin_name or "admin",
            action="DELETE_BUILDING",
            entity_type="Building",
            entity_id=building.id,
            admin_id=admin_id,
            old_values={"name": building.name, "code": building.code},
        )
        db.session.delete(building)
        db.session.commit()
        return {"deleted": True, "id": building.id}

    def list_buildings(
        self,
        query: str = None,
        building_type: str = None,
        area: str = None,
        status: str = "ACTIVE",
        min_lat: float = None,
        max_lat: float = None,
        min_lng: float = None,
        max_lng: float = None,
        limit: int = 100,
        offset: int = 0,
    ) -> tuple[list, int]:
        q = Building.query
        if status and status != "ALL":
            q = q.filter_by(status=status)
        if building_type and building_type != "ALL":
            q = q.filter_by(building_type=building_type)
        if area:
            q = q.filter_by(area=area)
        if query:
            term = f"%{query.strip()}%"
            q = q.filter(
                (Building.name.ilike(term)) |
                (Building.code.ilike(term)) |
                (Building.address.ilike(term)) |
                (Building.landmark.ilike(term)) |
                (Building.kannada_name.ilike(term))
            )
        if min_lat is not None and max_lat is not None:
            q = q.filter(Building.latitude.between(min_lat, max_lat))
        if min_lng is not None and max_lng is not None:
            q = q.filter(Building.longitude.between(min_lng, max_lng))

        total = q.count()
        buildings = q.order_by(Building.created_at.desc()).offset(offset).limit(limit).all()
        return [b.to_dict(include_children=False) for b in buildings], total

    def get_map_markers(self, building_type: str = None, query: str = None) -> list:
        """Lightweight marker payload for Leaflet OpenStreetMap."""
        q = Building.query.filter(Building.status == "ACTIVE")
        if building_type and building_type != "ALL":
            q = q.filter_by(building_type=building_type)
        if query:
            term = f"%{query.strip()}%"
            q = q.filter((Building.name.ilike(term)) | (Building.area.ilike(term)))

        buildings = q.all()
        markers = []
        for b in buildings:
            primary_photo = b.photos.filter_by(is_primary=True).first() or b.photos.first()
            markers.append({
                "id": b.id,
                "code": b.code,
                "name": b.name,
                "kannadaName": b.kannada_name,
                "latitude": b.latitude,
                "longitude": b.longitude,
                "buildingType": b.building_type,
                "commercialSubtype": b.commercial_subtype,
                "address": b.address,
                "area": b.area,
                "condition": b.building_condition,
                "unitsCount": b.units.count(),
                "totalFloors": b.total_floors,
                "floorsCount": b.floors.count(),
                "businessesCount": b.businesses.filter_by(status="ACTIVE").count() if hasattr(b, "businesses") else 0,
                "verificationStatus": b.location_verification_status,
                "primaryPhotoUrl": primary_photo.url if primary_photo else None,
            })
        return markers

    # Floor management
    def add_floor(self, building_id: str, floor_data: dict) -> Floor:
        building = self.get_building_by_id(building_id)
        floor_id = floor_data.get("id") or f"flr_{uuid.uuid4().hex[:10]}"
        floor = Floor(
            id=floor_id,
            building_id=building.id,
            floor_level=int(floor_data.get("floorLevel", 0)),
            floor_name=floor_data.get("floorName", "Ground Floor"),
            floor_usage=floor_data.get("floorUsage", "Commercial"),
            units_count=int(floor_data.get("unitsCount", 0)),
            notes=floor_data.get("notes"),
        )
        db.session.add(floor)
        # Update total floors if needed
        max_level = max([f.floor_level for f in building.floors] + [floor.floor_level])
        building.total_floors = max(building.total_floors, max_level + 1)
        db.session.commit()
        return floor

    # Unit management
    def add_unit(self, building_id: str, floor_id: str, unit_data: dict) -> Unit:
        unit_id = unit_data.get("id") or f"unt_{uuid.uuid4().hex[:10]}"
        unit = Unit(
            id=unit_id,
            building_id=building_id,
            floor_id=floor_id,
            unit_number=unit_data.get("unitNumber", "Shop 001"),
            unit_name=unit_data.get("unitName"),
            unit_type=unit_data.get("unitType", "Retail Shop"),
            usage=unit_data.get("usage", "Commercial"),
            occupancy_status=unit_data.get("occupancyStatus", "Occupied"),
            size_sqft=float(unit_data.get("sizeSqft")) if unit_data.get("sizeSqft") else None,
            notes=unit_data.get("notes"),
        )
        db.session.add(unit)

        # Update building counts
        building = Building.query.get(building_id)
        if building:
            if unit.usage == "Commercial":
                building.commercial_units_count += 1
            elif unit.usage == "Residential":
                building.residential_units_count += 1
            if unit.occupancy_status == "Vacant":
                building.vacant_units_count += 1

        db.session.commit()
        return unit

    def add_photo(self, building_id: str, photo_url: str, photo_type: str = "Front View", caption: str = None, is_primary: bool = False, surveyor_name: str = None) -> BuildingPhoto:
        photo = BuildingPhoto(
            id=f"bph_{uuid.uuid4().hex[:10]}",
            building_id=building_id,
            url=photo_url,
            photo_type=photo_type,
            caption=caption,
            is_primary=is_primary,
            surveyor_name=surveyor_name,
        )
        db.session.add(photo)
        db.session.commit()
        return photo

